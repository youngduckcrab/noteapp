// ws lock-age (docs/plans/m5-7/01-infra.md 4.2, 8.2 J20, 9.1 — P-C): the
// lock parser, the changed hosted entries, the pub API answer, the calendar
// day count (13 days → violation, 14 → ok), the warnings (network error,
// a version the API does not list, an unreadable answer, a base that is not
// a commit), and the command over a real git repository with a fake
// downloader and with the real one against a local server.

import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:test/test.dart';

import '../src/cli.dart';
import '../src/lock_age.dart';
import '../src/web_assets.dart' show Downloader, httpDownload;
import 'support/fixture_workspace.dart';

String _entry(
  String name,
  String version, {
  String source = 'hosted',
  String url = 'https://pub.dev',
}) => switch (source) {
  'hosted' =>
    '  $name:\n'
        '    dependency: transitive\n'
        '    description:\n'
        '      name: $name\n'
        '      sha256: "00"\n'
        '      url: "$url"\n'
        '    source: hosted\n'
        '    version: "$version"\n',
  'sdk' =>
    '  $name:\n'
        '    dependency: "direct main"\n'
        '    description: flutter\n'
        '    source: sdk\n'
        '    version: "0.0.0"\n',
  _ =>
    '  $name:\n'
        '    dependency: "direct main"\n'
        '    description:\n'
        '      path: "packages/$name"\n'
        '      relative: true\n'
        '    source: path\n'
        '    version: "$version"\n',
};

String _lock(List<String> entries) =>
    '# Generated by pub\n'
    'packages:\n'
    '${entries.join()}'
    'sdks:\n'
    '  dart: ">=3.12.0 <4.0.0"\n';

/// A pub API answer listing [published] (version → ISO time).
List<int> _api(String name, Map<String, String> published) => utf8.encode(
  jsonEncode({
    'name': name,
    'latest': {'version': published.keys.last},
    'versions': [
      for (final MapEntry(:key, :value) in published.entries)
        {'version': key, 'published': value, 'pubspec': <String, Object?>{}},
    ],
  }),
);

final _now = DateTime.utc(2026, 11, 6);

void main() {
  group('parseHostedPackages', () {
    test('hosted entries only, by name, with their server', () {
      final lock = _lock([
        _entry('args', '2.7.0'),
        _entry('flutter', '', source: 'sdk'),
        _entry('note_core', '0.1.0', source: 'path'),
        _entry('private_pkg', '1.0.0', url: 'https://pub.example.com/'),
      ]);
      final packages = parseHostedPackages(lock);
      expect(packages.keys, ['args', 'private_pkg']);
      expect(packages['args']!.version, '2.7.0');
      expect(
        packages['args']!.apiUri,
        Uri.parse('https://pub.dev/api/packages/args'),
      );
      expect(
        packages['private_pkg']!.apiUri,
        Uri.parse('https://pub.example.com/api/packages/private_pkg'),
      );
    });

    test('the workspace lock parses and has hosted entries', () {
      final lock = File(p.join(repoRoot, 'pubspec.lock')).readAsStringSync();
      final packages = parseHostedPackages(lock);
      expect(packages.length, greaterThan(100));
      expect(packages['yaml']!.url, 'https://pub.dev');
      expect(packages, isNot(contains('note_core'))); // a path member
    });

    test('not a lock → LockAgeException', () {
      for (final bad in [
        'packages: [',
        '- a list',
        'packages: 3',
        'packages:\n  a:\n    source: hosted\n    description: x\n',
      ]) {
        expect(
          () => parseHostedPackages(bad),
          throwsA(isA<LockAgeException>()),
          reason: bad,
        );
      }
      expect(parseHostedPackages('sdks:\n  dart: any\n'), isEmpty);
    });
  });

  group('changedHostedPackages', () {
    final before = _lock([
      _entry('args', '2.7.0'),
      _entry('meta', '1.17.0'),
      _entry('old_pkg', '1.0.0'),
      _entry('path', '1.9.1'),
    ]);

    test('new and re-versioned entries, in name order; same or removed ones '
        'are not', () {
      final after = _lock([
        _entry('xml', '7.0.1'), // new
        _entry('args', '2.7.0'), // same
        _entry('meta', '1.18.0'), // new version
        _entry('path', '1.9.1', url: 'https://pub.example.com'), // new server
        _entry('another', '0.1.0', source: 'path'), // not hosted
      ]);
      expect(changedHostedPackages(before, after).map((e) => '$e'), [
        'meta 1.18.0',
        'path 1.9.1',
        'xml 7.0.1',
      ]);
    });

    test('no lock at the base: every hosted entry', () {
      expect(changedHostedPackages(null, before).map((e) => e.name), [
        'args',
        'meta',
        'old_pkg',
        'path',
      ]);
    });

    test('nothing changed: empty', () {
      expect(changedHostedPackages(before, before), isEmpty);
    });
  });

  group('publishedOf', () {
    final answer = utf8.decode(
      _api('record', {
        '7.1.1': '2026-09-01T08:00:00.000Z',
        '7.1.2': '2026-10-09T17:12:44.123Z',
      }),
    );

    test('the version\'s published time', () {
      expect(
        publishedOf(answer, '7.1.2'),
        DateTime.utc(2026, 10, 9, 17, 12, 44, 123),
      );
      expect(publishedOf(answer, '7.1.1'), DateTime.utc(2026, 9, 1, 8));
    });

    test('a version the answer does not list, or a broken answer → null', () {
      expect(publishedOf(answer, '9.9.9'), isNull);
      for (final broken in [
        'not json',
        '[]',
        '{"versions": 3}',
        '{"versions": [{"version": "1.0.0", "published": 7}]}',
        '{"versions": [{"version": "1.0.0", "published": "yesterday"}]}',
      ]) {
        expect(publishedOf(broken, '1.0.0'), isNull, reason: broken);
      }
    });
  });

  test('calendarDaysBetween counts UTC dates, not hours', () {
    expect(calendarDaysBetween(DateTime.utc(2026, 10, 23, 23, 59), _now), 14);
    expect(calendarDaysBetween(DateTime.utc(2026, 10, 24), _now), 13);
    expect(
      calendarDaysBetween(
        DateTime.utc(2026, 10, 24, 0, 1),
        DateTime.utc(2026, 11, 6, 23, 59),
      ),
      13,
    );
    // A local time is taken in UTC.
    expect(
      calendarDaysBetween(DateTime.parse('2026-10-24T01:00:00+09:00'), _now),
      14,
    );
  });

  group('checkLockAge', () {
    final base = _lock([_entry('args', '2.7.0')]);
    final lock = _lock([
      _entry('args', '2.7.0'),
      _entry('fresh', '1.0.1'), // published 13 days before now
      _entry('settled', '2.0.0'), // 14 days
      _entry('offline', '1.0.0'), // network error
      _entry('throws', '1.0.0'), // the downloader throws
      _entry('unlisted', '3.0.0'), // the API does not list the version
      _entry('garbled', '1.0.0'), // not JSON
    ]);
    final asked = <Uri>[];
    Future<List<int>?> fetch(Uri url) async {
      asked.add(url);
      return switch (url.pathSegments.last) {
        'fresh' => _api('fresh', {
          '1.0.0': '2026-01-01T00:00:00Z',
          '1.0.1': '2026-10-24T09:00:00Z',
        }),
        'settled' => _api('settled', {'2.0.0': '2026-10-23T18:00:00Z'}),
        'offline' => null,
        'throws' => throw const SocketException('no route'),
        'unlisted' => _api('unlisted', {'2.9.0': '2026-01-01T00:00:00Z'}),
        'garbled' => utf8.encode('<html>'),
        _ => fail('unexpected request $url'),
      };
    }

    setUp(asked.clear);

    test('13 days → too new, 14 → ok, unreadable → warnings; one request '
        'per changed package', () async {
      final report = await checkLockAge(
        baseLock: base,
        lock: lock,
        fetch: fetch,
        now: _now,
      );
      expect(asked.map((u) => u.path), [
        '/api/packages/fresh',
        '/api/packages/garbled',
        '/api/packages/offline',
        '/api/packages/settled',
        '/api/packages/throws',
        '/api/packages/unlisted',
      ]);
      final outcomes = {
        for (final e in report.entries) e.package.name: (e.outcome, e.days),
      };
      expect(outcomes, {
        'fresh': (LockAgeOutcome.tooNew, 13),
        'garbled': (LockAgeOutcome.unknown, null),
        'offline': (LockAgeOutcome.unknown, null),
        'settled': (LockAgeOutcome.ok, 14),
        'throws': (LockAgeOutcome.unknown, null),
        'unlisted': (LockAgeOutcome.unknown, null),
      });
      expect(report.violations.map((e) => e.package.name), ['fresh']);
      expect(report.warningCount, 4);

      final text = report.format(since: 'origin/main');
      expect(
        text,
        contains(
          '6 hosted package(s) new or changed since origin/main (rule: '
          'published at least 14 day(s) before 2026-11-06):',
        ),
      );
      expect(text, contains('| fresh | 1.0.1 | 2026-10-24 | 13 | too new |'));
      expect(text, contains('| settled | 2.0.0 | 2026-10-23 | 14 | ok |'));
      expect(text, contains('| offline | 1.0.0 | ? | ? | unknown |'));
      expect(
        text,
        contains(
          'violation: fresh 1.0.1 was published 2026-10-24, 13 day(s) '
          'before 2026-11-06 (< 14)',
        ),
      );
      expect(
        text,
        contains(
          'warning: offline 1.0.0: could not read '
          'https://pub.dev/api/packages/offline',
        ),
      );
      expect(text, contains('warning: throws 1.0.0: could not read'));
      expect(text, contains('no route'));
      expect(text, contains('does not give the publication time'));
      expect(
        text.trimRight().split('\n').last,
        'ws lock-age: 1 violation(s), 4 warning(s)',
      );
    });

    test('--min-days moves the line', () async {
      final strict = await checkLockAge(
        baseLock: base,
        lock: lock,
        fetch: fetch,
        now: _now,
        minDays: 15,
      );
      expect(strict.violations.map((e) => e.package.name), [
        'fresh',
        'settled',
      ]);
      final loose = await checkLockAge(
        baseLock: base,
        lock: lock,
        fetch: fetch,
        now: _now,
        minDays: 13,
      );
      expect(loose.violations, isEmpty);
    });

    test('nothing changed: no request, one line', () async {
      final report = await checkLockAge(
        baseLock: lock,
        lock: lock,
        fetch: fetch,
        now: _now,
      );
      expect(asked, isEmpty);
      expect(
        report.format(since: 'HEAD'),
        'No hosted package is new or changed since HEAD.\n'
        'ws lock-age: 0 violation(s), 0 warning(s)\n',
      );
    });
  });

  group('ws lock-age', () {
    late Directory repo;

    Future<void> git(List<String> args) async {
      final r = await Process.run('git', [
        '-c',
        'user.name=t',
        '-c',
        'user.email=t@example.invalid',
        '-c',
        'commit.gpgsign=false',
        ...args,
      ], workingDirectory: repo.path);
      expect(r.exitCode, 0, reason: '${r.stdout}${r.stderr}');
    }

    void writeLock(List<String> entries) =>
        File(p.join(repo.path, 'pubspec.lock'))
            .writeAsStringSync(_lock(entries));

    setUp(() async {
      repo = Directory.systemTemp.createTempSync('ws_lock_age_');
      addTearDown(() => repo.deleteSync(recursive: true));
      await git(['init', '-q', '-b', 'main']);
      writeLock([_entry('args', '2.7.0')]);
      await git(['add', 'pubspec.lock']);
      await git(['commit', '-q', '-m', 'base']);
    });

    Future<(int, String, String)> ws(
      List<String> args, {
      required Downloader download,
      Map<String, String> environment = const {},
    }) async {
      final out = StringBuffer();
      final err = StringBuffer();
      final code = await runWs(
        ['--root', repo.path, 'lock-age', ...args],
        context: WsContext(
          out: out,
          err: err,
          download: download,
          environment: {...Platform.environment, ...environment},
          now: () => DateTime.utc(2030),
        ),
      );
      return (code, '$out', '$err');
    }

    Future<List<int>?> pubDev(Uri url) async => switch (url.pathSegments.last) {
      'fresh' => _api('fresh', {'1.0.0': '2026-10-24T00:00:00Z'}),
      'settled' => _api('settled', {'1.0.0': '2026-10-23T00:00:00Z'}),
      _ => null,
    };

    test('a package published 13 days before --now → exit 1', () async {
      writeLock([_entry('args', '2.7.0'), _entry('fresh', '1.0.0')]);
      final (code, out, _) = await ws([
        '--since',
        'HEAD',
        '--now',
        '2026-11-06',
      ], download: pubDev);
      expect(code, 1, reason: out);
      expect(out, contains('violation: fresh 1.0.0'));
      expect(out, endsWith('ws lock-age: 1 violation(s), 0 warning(s)\n'));
    });

    test('14 days → exit 0; the summary file gets the table', () async {
      writeLock([_entry('args', '2.7.0'), _entry('settled', '1.0.0')]);
      final summary = File(p.join(repo.path, 'summary.md'));
      final (code, out, _) = await ws(
        ['--since', 'HEAD', '--now', '2026-11-06'],
        download: pubDev,
        environment: {'GITHUB_STEP_SUMMARY': summary.path},
      );
      expect(code, 0, reason: out);
      expect(out, contains('| settled | 1.0.0 | 2026-10-23 | 14 | ok |'));
      expect(
        summary.readAsStringSync(),
        startsWith('### Lock age (since HEAD)\n\n'),
      );
      expect(summary.readAsStringSync(), contains('| settled | 1.0.0 |'));
    });

    test('a network error is a warning: exit 0', () async {
      writeLock([_entry('args', '2.7.0'), _entry('offline', '1.0.0')]);
      final (code, out, _) = await ws([
        '--since',
        'HEAD',
        '--now',
        '2026-11-06',
      ], download: pubDev);
      expect(code, 0, reason: out);
      expect(out, contains('warning: offline 1.0.0: could not read'));
      expect(out, endsWith('ws lock-age: 0 violation(s), 1 warning(s)\n'));
    });

    test('without --now: the clock of the context', () async {
      writeLock([_entry('args', '2.7.0'), _entry('fresh', '1.0.0')]);
      final (code, out, _) = await ws(['--since', 'HEAD'], download: pubDev);
      expect(code, 0, reason: out); // 2030: long published
      expect(out, contains('before 2030-01-01'));
    });

    test('the base is a ref of the repository; a ref without the lock makes '
        'every hosted entry new', () async {
      await git(['rm', '-q', 'pubspec.lock']);
      await git(['commit', '-q', '-m', 'no lock']);
      writeLock([_entry('args', '2.7.0'), _entry('settled', '1.0.0')]);
      var (code, out, _) = await ws([
        '--since',
        'HEAD',
        '--now',
        '2026-11-06',
      ], download: pubDev);
      expect(code, 0, reason: out);
      // args has no answer in the fake: a warning, not a failure.
      expect(out, contains('2 hosted package(s) new or changed since HEAD'));
      (code, out, _) = await ws([
        '--since',
        'HEAD~1',
        '--now',
        '2026-11-06',
      ], download: pubDev);
      expect(code, 0, reason: out);
      expect(out, contains('1 hosted package(s) new or changed since HEAD~1'));
    });

    test('a ref that is not a commit: a warning, nothing compared', () async {
      final (code, out, _) = await ws([
        '--since',
        'origin/nowhere',
      ], download: (_) => fail('no request'));
      expect(code, 0);
      expect(
        out,
        'warning: `origin/nowhere` is not a commit — nothing compared\n'
        'ws lock-age: 0 violation(s), 1 warning(s)\n',
      );
    });

    test('usage errors → exit 2', () async {
      Future<List<int>?> none(Uri _) async => null;
      for (final args in [
        <String>[],
        ['--since', ''],
        ['--since', 'HEAD', '--min-days', 'x'],
        ['--since', 'HEAD', '--min-days', '-1'],
        ['--since', 'HEAD', '--now', '2026-13-40'],
        ['--since', 'HEAD', '--now', 'today'],
        ['--since', 'HEAD', 'extra'],
      ]) {
        final (code, _, err) = await ws(args, download: none);
        expect(code, 2, reason: '$args $err');
      }
    });

    test('no pubspec.lock in the root → exit 3', () async {
      File(p.join(repo.path, 'pubspec.lock')).deleteSync();
      final (code, _, err) = await ws([
        '--since',
        'HEAD',
      ], download: (_) async => null);
      expect(code, 3);
      expect(err, contains('no pubspec.lock'));
    });

    test('the real downloader against a local server: an answer, then a '
        'closed port (network error → warning)', () async {
      final server = await HttpServer.bind(InternetAddress.loopbackIPv4, 0);
      final requests = <String>[];
      server.listen((request) {
        requests.add(request.uri.path);
        request.response
          ..headers.contentType = ContentType.json
          ..add(_api('local_pkg', {'1.2.0': '2026-10-01T00:00:00Z'}))
          ..close();
      });
      final url = 'http://127.0.0.1:${server.port}';
      writeLock([
        _entry('args', '2.7.0'),
        _entry('local_pkg', '1.2.0', url: url),
      ]);
      var (code, out, _) = await ws([
        '--since',
        'HEAD',
        '--now',
        '2026-11-06',
      ], download: httpDownload);
      expect(code, 0, reason: out);
      expect(requests, ['/api/packages/local_pkg']);
      expect(out, contains('| local_pkg | 1.2.0 | 2026-10-01 | 36 | ok |'));

      await server.close(force: true);
      (code, out, _) = await ws([
        '--since',
        'HEAD',
        '--now',
        '2026-11-06',
      ], download: httpDownload);
      expect(code, 0, reason: out);
      expect(out, contains('warning: local_pkg 1.2.0: could not read $url'));
    });
  });
}
